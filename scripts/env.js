#!/usr/bin/env node
/**
 * env.js - turns .env into _config.local.yml for local builds.
 *
 * .env holds your supabase project and the chat function name.
 * this script writes the two values jekyll needs, so the widget can be
 * tested locally without pasting keys into the tracked _config.yml.
 *
 * .env is gitignored. _config.local.yml is gitignored. neither is published.
 *
 * usage:
 *   node scripts/env.js
 *   RUBYOPT="-r./scripts/ruby4-compat.rb" bundle exec jekyll build \
 *     --config _config.yml,_config.local.yml
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ENV_FILE = path.join(ROOT, '.env');
const OUT_FILE = path.join(ROOT, '_config.local.yml');

function parse(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (key) out[key] = value;
  }
  return out;
}

function main() {
  if (!fs.existsSync(ENV_FILE)) {
    console.error('no .env found. copy .env.example to .env and fill it in.');
    process.exit(1);
  }

  const env = parse(fs.readFileSync(ENV_FILE, 'utf8'));
  const base = (env.SUPABASE_URL || '').replace(/\/+$/, '');
  const key = env.SUPABASE_ANON_KEY || '';
  const fn = env.CHAT_FUNCTION || 'ramani-chat';

  const missing = [];
  if (!base) missing.push('SUPABASE_URL');
  if (!key) missing.push('SUPABASE_ANON_KEY');
  if (missing.length) {
    console.error('missing in .env: ' + missing.join(', '));
    process.exit(1);
  }

  const endpoint = `${base}/functions/v1/${fn}`;

  const yaml = [
    '# generated by scripts/env.js from .env. do not edit, do not commit.',
    'chat:',
    `  endpoint: "${endpoint}"`,
    `  key: "${key}"`,
    '',
  ].join('\n');

  fs.writeFileSync(OUT_FILE, yaml);
  console.log('wrote _config.local.yml');
  console.log('  endpoint: ' + endpoint);
  console.log('  key: ' + key.slice(0, 8) + '...' + key.slice(-6));

  if (!env.DEEPSEEK_API_KEY || /your|placeholder|sk-\.\.\./i.test(env.DEEPSEEK_API_KEY)) {
    console.log('');
    console.log('note: DEEPSEEK_API_KEY is not set in .env.');
    console.log('the deployed function reads it from supabase secrets, not from here:');
    console.log('  supabase secrets set DEEPSEEK_API_KEY=sk-...');
  }
}

main();
